create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  phone text unique,
  currency text not null default 'BRL' check (currency in ('BRL','USD','EUR')),
  language text not null default 'pt-BR' check (language in ('pt-BR','en-US','es-ES')),
  dark_mode boolean not null default false,
  hide_balance boolean not null default false,
  notifications_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  color text not null default '#c8e5dd',
  budget numeric(14,2) not null default 0 check (budget >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, name)
);

create table if not exists public.debts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  value numeric(14,2) not null check (value > 0),
  due_date date not null,
  reminder_date date,
  category_id bigint references public.categories(id) on delete set null,
  month_key date not null,
  paid boolean not null default false,
  paid_at timestamptz,
  payment_method text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (reminder_date is null or reminder_date <= due_date)
);

create table if not exists public.monthly_budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  month date not null,
  amount numeric(14,2) not null default 0 check (amount >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, month)
);

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null,
  target numeric(14,2) not null check (target > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.goal_deposits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_id bigint not null references public.goals(id) on delete cascade,
  month date not null,
  amount numeric(14,2) not null check (amount <> 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_categories_user on public.categories(user_id);
create index if not exists idx_debts_user on public.debts(user_id);
create index if not exists idx_debts_user_month on public.debts(user_id, month_key);
create index if not exists idx_monthly_budgets_user_month on public.monthly_budgets(user_id, month);
create index if not exists idx_goals_user on public.goals(user_id);
create index if not exists idx_goal_deposits_goal on public.goal_deposits(goal_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at = now(); return new; end; $$;

DROP TRIGGER IF EXISTS profiles_updated_at ON public.profiles;
CREATE TRIGGER profiles_updated_at BEFORE UPDATE ON public.profiles FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
DROP TRIGGER IF EXISTS categories_updated_at ON public.categories;
CREATE TRIGGER categories_updated_at BEFORE UPDATE ON public.categories FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
DROP TRIGGER IF EXISTS debts_updated_at ON public.debts;
CREATE TRIGGER debts_updated_at BEFORE UPDATE ON public.debts FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
DROP TRIGGER IF EXISTS monthly_budgets_updated_at ON public.monthly_budgets;
CREATE TRIGGER monthly_budgets_updated_at BEFORE UPDATE ON public.monthly_budgets FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
DROP TRIGGER IF EXISTS goals_updated_at ON public.goals;
CREATE TRIGGER goals_updated_at BEFORE UPDATE ON public.goals FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, name, phone)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', split_part(coalesce(new.email,''), '@', 1)), new.raw_user_meta_data->>'phone');
  return new;
end;
$$;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

